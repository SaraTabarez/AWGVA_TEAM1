package mx.edu.utez.awgva.Model;

public class FirmantesOficiales {
    private String directorNombre;
    private String directorCargo;
    private String docenteNombre;
    private String docenteCargo;
    private String estadiasNombre;
    private String estadiasCargo;

    public String getDirectorNombre() { return directorNombre; }
    public void setDirectorNombre(String directorNombre) { this.directorNombre = directorNombre; }
    public String getDirectorCargo() { return directorCargo; }
    public void setDirectorCargo(String directorCargo) { this.directorCargo = directorCargo; }
    public String getDocenteNombre() { return docenteNombre; }
    public void setDocenteNombre(String docenteNombre) { this.docenteNombre = docenteNombre; }
    public String getDocenteCargo() { return docenteCargo; }
    public void setDocenteCargo(String docenteCargo) { this.docenteCargo = docenteCargo; }
    public String getEstadiasNombre() { return estadiasNombre; }
    public void setEstadiasNombre(String estadiasNombre) { this.estadiasNombre = estadiasNombre; }
    public String getEstadiasCargo() { return estadiasCargo; }
    public void setEstadiasCargo(String estadiasCargo) { this.estadiasCargo = estadiasCargo; }
}